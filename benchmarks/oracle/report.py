def spotcheck_section(sc):
    L = []
    w = L.append
    w("## Spot-check")
    w("")
    w("Everything below was read by hand against the source at the call site (seed %s; cells %s)." % (sc.get("seed"), ", ".join(sc.get("cells", []))))
    w("")
    w("**Committed edges.** 20 random wrong edges (FP) and 20 random missed edges (FN) per language. Verdicts: `lidx_error` "
      "(lidx is wrong or missed a real call), `oracle_artefact` (the compiler graph is not the right judge), `matching_artefact` "
      "(our matching rule mis-keyed a declaration).")
    w("")
    w("| Language | Sample | lidx_error | oracle_artefact | matching_artefact | artefact rate [95% Wilson CI] |")
    w("|---|---|---:|---:|---:|---|")
    tot_a = tot_n = 0
    for lang, kinds in sc["languages"].items():
        lt = {"lidx_error": 0, "oracle_artefact": 0, "matching_artefact": 0}
        for kind in ("fp", "fn"):
            items = kinds[kind]
            c = {k: sum(1 for i in items if i["verdict"] == k) for k in lt}
            for k in lt:
                lt[k] += c[k]
            n = len(items)
            art = c["oracle_artefact"] + c["matching_artefact"]
            w("| %s | %s (n=%d) | %d | %d | %d | %d/%d = %.1f%% %s |" % (lang, kind.upper(), n, c["lidx_error"], c["oracle_artefact"],
                                                                  c["matching_artefact"], art, n, 100 * art / max(n, 1), ci_pct(art, n)))
        n = sum(lt.values())
        art = lt["oracle_artefact"] + lt["matching_artefact"]
        tot_a += art
        tot_n += n
        w("| %s | both (n=%d) | %d | %d | %d | **%d/%d = %.1f%%** %s |" % (lang, n, lt["lidx_error"], lt["oracle_artefact"], lt["matching_artefact"],
                                                                    art, n, 100 * art / max(n, 1), ci_pct(art, n)))
    w("")
    bk = sc.get("buckets", {})
    if bk:
        w("**Exclusion buckets.** Up to 10 random items from every bucket that removes edges from precision or recall, per language. "
          "Verdicts: `correct_exclusion` (the bucket rule is right for this item) or `misbucketed` (the item should have been "
          "graded, so the exclusion flatters or hides something).")
        w("")
        w("| Language | Bucket | Bucket size | Sampled | misbucketed | rate [95% Wilson CI] |")
        w("|---|---|---:|---:|---:|---|")
        bm = bn = 0
        for lang, names in bk.items():
            for name, items in names.items():
                n = len(items)
                if not n:
                    continue
                mb = sum(1 for i in items if i["verdict"] == "misbucketed")
                bm += mb
                bn += n
                w("| %s | %s | %d | %d | %d | %.1f%% %s |" % (lang, name, items[0]["bucket_size"], n, mb, 100 * mb / n, ci_pct(mb, n)))
        w("| all | all buckets | | %d | %d | **%.1f%%** %s |" % (bn, bm, 100 * bm / max(bn, 1), ci_pct(bm, bn)))
        w("")
        tot_a += bm
        tot_n += bn
    w("Pooled over every sampled item: %d/%d = %.1f%% %s." % (tot_a, tot_n, 100 * tot_a / max(tot_n, 1), ci_pct(tot_a, tot_n)))
    w("")
    w(sc.get("notes", ""))
    w("")
    for lang, kinds in sc["languages"].items():
        w("### %s samples" % lang)
        w("")
        for kind in ("fp", "fn"):
            w("**%s**" % kind.upper())
            w("")
            for i in kinds[kind]:
                w("- `%s` %s -> %s: **%s**, %s" % (i["id"], i["caller"], i["callee"], i["verdict"], i["note"]))
            w("")
        for name, items in bk.get(lang, {}).items():
            w("**bucket %s**" % name)
            w("")
            for i in items:
                w("- `%s` %s -> %s: **%s**, %s" % (i["id"], i["caller"], i["callee"], i["verdict"], i["note"]))
            w("")
    return "\n".join(L)


def ci_pct(k, n):
    lo, hi = wilson(k, n)
    return "[%.1f%%, %.1f%%]" % (100 * lo, 100 * hi) if lo is not None else ""
