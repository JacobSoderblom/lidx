"""Markdown report for the oracle benchmark. Python 3 stdlib only."""
import json
import os

# Published by repowise (docs/BENCHMARKS.md on main, 2026-10-03): precision, recall.
# "Call graph against a compiler" table for Go/TypeScript, "Accuracy by language"
# table (rust-analyzer key) for Rust. cobra without tests and the TypeScript
# with-tests variants are not published.
REPOWISE = {
    "go/cobra/tests": (0.995, 0.705, None),
    "go/gitleaks/no_tests": (0.991, 0.971, None),
    "go/gitleaks/tests": (0.989, 0.939, None),
    "go/syft/no_tests": (0.979, 0.539, None),
    "go/syft/tests": (0.982, 0.341, None),
    "ts/zod": (0.995, 0.796, 1269),
    "ts/hono": (0.976, 0.806, 706),
    "rust/ripgrep": (0.852, 0.532, 4555),
    "rust/fd": (0.899, 0.619, 231),
}

ORDER = ["go/cobra/tests", "go/cobra/no_tests", "go/gitleaks/no_tests", "go/gitleaks/tests", "go/syft/no_tests", "go/syft/tests",
         "ts/zod", "ts/hono", "rust/ripgrep", "rust/fd"]


def pct(x):
    return "-" if x is None else "%.3f" % x


def ci(c):
    return "-" if not c or c[0] is None else "[%.3f, %.3f]" % (c[0], c[1])


def build(results_dir):
    meta = json.load(open(os.path.join(results_dir, "cells.json")))
    cells = meta["cells"]
    L = []
    w = L.append
    w("# lidx call graph against compilers")
    w("")
    w("Generated by `benchmarks/oracle/run.py`. lidx `%s`, built from main `%s` (%s). Method, toolchains and caveats: "
      "[README.md](../README.md)." % (meta["lidx_version"], meta["main_commit"][:10], meta["generated"]))
    w("")
    w("Each cell is lidx's resolved CALLS edges graded against the answer a compiler gives for the same checkout. "
      "Precision = lidx edges the compiler confirms / lidx edges the compiler can judge. Recall = compiler edges lidx found / "
      "compiler edges whose caller lidx indexes. Intervals are 95% Wilson. repowise columns are the numbers repowise "
      "published (their `docs/BENCHMARKS.md`, 2026-10-03), for orientation only: corpus commits, scoping and dedup are not "
      "identical.")
    w("")
    w("## Headline")
    w("")
    w("| Cell | Oracle | Oracle edges (n) | Graded lidx edges (n) | lidx precision | 95% CI | lidx recall | 95% CI | repowise P / R |")
    w("|---|---|---:|---:|---:|---|---:|---|---|")
    for cid in ORDER:
        c = cells.get(cid)
        if not c:
            continue
        s = c["calls"]
        rw = REPOWISE.get(cid)
        rws = "%.3f / %.3f" % (rw[0], rw[1]) if rw else "not published"
        w("| %s | %s | %d | %d | %s | %s | %s | %s | %s |" % (
            cid, {"go": "Go RTA", "ts": "tsc", "rust": "rust-analyzer SCIP"}[c["lang"]], s["oracle_edges_caller_indexed"], s["graded"],
            pct(s["precision"]), ci(s["precision_ci"]), pct(s["recall"]), ci(s["recall_ci"]), rws))
    w("")
    w("`tests` = test files are part of the analysed program and test functions are roots; `no_tests` = production code only "
      "(roots: `main`, or for a library with no `main` package its exported surface). lidx indexes the whole repository once; "
      "edges from files or functions the compiler did not analyse are excluded from precision and listed below as ungradable.")
    w("")
    w("### Counting rules in one place")
    w("")
    w("- Oracle edges are distinct (caller declaration, callee declaration) pairs; lidx edges are deduplicated the same way.")
    w("- Callee outside the repository: not judged on either side.")
    w("- Oracle edge whose caller is not a symbol lidx indexes: reported as a **capture gap**, kept out of the recall denominator "
      "and shown in its own column below (`recall incl. gap` puts them back).")
    w("- lidx edge the compiler could not judge (caller file or function not in the analysed program, callee file not analysed, "
      "or a call site the compiler left unresolved): not counted for precision, listed under *ungradable*.")
    w("")
    w("## Alongside REFERENCES")
    w("")
    w("Same grading with lidx's REFERENCES edges added to CALLS (the compiler graph contains calls only, so extra reference "
      "edges can only cost precision; they can win recall where lidx records a call as a reference).")
    w("")
    w("| Cell | CALLS P | CALLS R | CALLS+REFERENCES P | CALLS+REFERENCES R | REFERENCES edges in db |")
    w("|---|---:|---:|---:|---:|---:|")
    for cid in ORDER:
        c = cells.get(cid)
        if not c:
            continue
        r = c["calls_plus_references"]
        w("| %s | %s | %s | %s | %s | %d |" % (cid, pct(c["calls"]["precision"]), pct(c["calls"]["recall"]), pct(r["precision"]),
                                              pct(r["recall"]), c["lidx_edge_counts"]["REFERENCES"]))
    w("")
    w("## Per cell")
    for cid in ORDER:
        c = cells.get(cid)
        if not c:
            continue
        s = c["calls"]
        w("")
        w("### %s" % cid)
        w("")
        w("- oracle: %s, %d edges; %d caller-indexed, %d capture gap; recall incl. gap %s" % (
            c.get("oracle_mode"), s["oracle_edges"], s["oracle_edges_caller_indexed"], s["capture_gap_edges"], pct(s["recall_incl_capture_gap"])))
        w("- lidx: %d resolved in-repo CALLS pairs; %d graded (%d correct, %d wrong); lidx indexed in %ss" % (
            s["lidx_pairs_total"], s["graded"], s["tp"], s["fp"], c["index_seconds"]))
        if s["ungradable"]:
            w("- ungradable lidx pairs: " + ", ".join("%s %d" % kv for kv in sorted(s["ungradable"].items())))
        w("")
        w("| resolution_kind | graded | correct | precision | 95% CI |")
        w("|---|---:|---:|---:|---|")
        for k, v in s["by_resolution_kind"].items():
            w("| %s | %d | %d | %s | %s |" % (k, v["graded"], v["tp"], pct(v["precision"]), ci(v["ci"])))
        w("")
        w("Wrong edges (FP) by category: " + (", ".join("%s %d" % kv for kv in s["fp_categories"].items()) or "none"))
        w("")
        w("Missed edges (FN) by category: " + (", ".join("%s %d" % kv for kv in s["fn_categories"].items()) or "none"))
        w("")
        fid = cid.replace("/", "__")
        w("Lists: `results/lists/%s.fn.json`, `%s.fp.json`, `%s.capture_gap.json`." % (fid, fid, fid))
    sc = os.path.join(results_dir, "spotcheck.json")
    if os.path.exists(sc):
        w("")
        w(spotcheck_section(json.load(open(sc))))
    w("")
    open(os.path.join(results_dir, "report.md"), "w").write("\n".join(L))
    print("wrote", os.path.join(results_dir, "report.md"))


def spotcheck_section(sc):
    L = []
    w = L.append
    w("## Spot-check")
    w("")
    w("20 random wrong edges (FP) and 20 random missed edges (FN) per language were read by hand against the source "
      "(sample: seed %s, cells %s). Verdicts: `lidx_error` (lidx is wrong or missed a real call), `oracle_artefact` "
      "(the compiler graph is not the right judge: dispatch fan-out, reflection, generated code, ...), `matching_artefact` "
      "(our matching rule mis-keyed a declaration)." % (sc.get("seed"), ", ".join(sc.get("cells", []))))
    w("")
    w("| Language | Sample | lidx_error | oracle_artefact | matching_artefact | artefact rate |")
    w("|---|---|---:|---:|---:|---:|")
    for lang, kinds in sc["languages"].items():
        tot = {"lidx_error": 0, "oracle_artefact": 0, "matching_artefact": 0}
        for kind in ("fp", "fn"):
            items = kinds[kind]
            c = {k: sum(1 for i in items if i["verdict"] == k) for k in tot}
            for k in tot:
                tot[k] += c[k]
            n = len(items)
            w("| %s | %s (n=%d) | %d | %d | %d | %.0f%% |" % (lang, kind.upper(), n, c["lidx_error"], c["oracle_artefact"],
                                                           c["matching_artefact"], 100 * (c["oracle_artefact"] + c["matching_artefact"]) / max(n, 1)))
        n = sum(tot.values())
        w("| %s | both (n=%d) | %d | %d | %d | **%.1f%%** |" % (lang, n, tot["lidx_error"], tot["oracle_artefact"], tot["matching_artefact"],
                                                           100 * (tot["oracle_artefact"] + tot["matching_artefact"]) / max(n, 1)))
    w("")
    w(sc.get("notes", ""))
    w("")
    for lang, kinds in sc["languages"].items():
        w("### %s samples" % lang)
        w("")
        for kind in ("fp", "fn"):
            w("**%s**" % kind.upper())
            w("")
            for i in kinds[kind]:
                w("- `%s` %s -> %s: **%s**, %s" % (i["id"], i["caller"], i["callee"], i["verdict"], i["note"]))
            w("")
    return "\n".join(L)
