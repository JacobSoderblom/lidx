"""Markdown report for the oracle benchmark. Python 3 stdlib only."""
import json
import os

# repowise's published point estimates (precision, recall) from docs/BENCHMARKS.md on repowise main (2026-10-03): the
# "Call graph against a compiler, five tools" table for Go and TypeScript and "Accuracy by language" (rust-analyzer
# key) for Rust. The counts behind each estimate come from the same cells' artifacts in repowise-bench
# (graph/experiments/g4-oracle-anchored and g9-language-oracles): recall n is the compiler edge count, precision n is
# matched + contradicted. Those artifacts are an earlier run of the same cells, so the intervals below are Wilson
# intervals computed by us from the published point estimate and that n, not intervals repowise published.
# cobra without tests and the TypeScript with-tests variants are not published.
REPOWISE = {
    #                         P      R     n_recall  n_precision
    "go/cobra/tests":         (0.995, 0.705, 2059, 1449),
    "go/gitleaks/no_tests":   (0.991, 0.971, 1584, 1550),
    "go/gitleaks/tests":      (0.989, 0.939, 1747, 1640),
    "go/syft/no_tests":       (0.979, 0.539, 7898, 4299),
    "go/syft/tests":          (0.982, 0.341, 22590, 7648),
    "ts/zod":                 (0.995, 0.796, 1269, 899),
    "ts/hono":                (0.976, 0.806, 706, 528),
    "rust/ripgrep/path_tests_excluded": (0.852, 0.532, 4555, 2520),
    "rust/fd/path_tests_excluded":      (0.899, 0.619, 231, 139),
}

ORDER = ["go/cobra/tests", "go/cobra/no_tests", "go/gitleaks/no_tests", "go/gitleaks/tests", "go/syft/no_tests", "go/syft/tests",
         "ts/zod", "ts/hono", "rust/ripgrep/path_tests_excluded", "rust/ripgrep/no_tests", "rust/ripgrep/tests",
         "rust/fd/path_tests_excluded", "rust/fd/no_tests", "rust/fd/tests"]


def comparable(c):
    """The grading that is set against repowise: TypeScript uses repowise's scope, the others the cell's own grading."""
    return c.get("comparable", c["calls"])


def wilson(k, n, z=1.96):
    import math
    if not n:
        return [None, None]
    p = k / n
    d = 1 + z * z / n
    c = (p + z * z / (2 * n)) / d
    h = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / d
    return [max(0.0, c - h), min(1.0, c + h)]


def rw_ci(p, n):
    return wilson(round(p * n), n)


def verdict(ours, theirs):
    """ahead / behind / tied by 95% interval overlap, never by point estimate."""
    if ours[0] > theirs[1]:
        return "ahead"
    if ours[1] < theirs[0]:
        return "behind"
    return "tied"


def pct(x):
    return "-" if x is None else "%.3f" % x


def ci(c):
    return "-" if not c or c[0] is None else "[%.3f, %.3f]" % (c[0], c[1])


def build(results_dir):
    meta = json.load(open(os.path.join(results_dir, "cells.json")))
    cells = meta["cells"]
    L = []
    w = L.append
    w("# lidx call graph against compilers")
    w("")
    w("Generated by `benchmarks/oracle/run.py`. lidx `%s`, built from main `%s` (%s). Method, toolchains and caveats: "
      "[README.md](../README.md)." % (meta["lidx_version"], meta["main_commit"][:10], meta["generated"]))
    w("")
    w("Each cell is lidx's resolved CALLS edges graded against the answer a compiler gives for the same checkout, "
      "at the commits and scope repowise pins for the same cells. Intervals are 95% Wilson.")
    w("")
    w("## Head-to-head with repowise")
    w("")
    w("Every row grades lidx the way repowise grades its own tool, so the verdicts are neither flattered nor penalised by scope. "
      "Precision = lidx edges the compiler confirms / lidx edges the compiler can judge. Recall = compiler edges "
      "matched (dispatch edges included) / **all** in-scope compiler edges, capture gaps and unindexed callees "
      "charged to lidx: the denominator repowise uses. The scope differences handled here:")
    w("")
    w("- **TypeScript**: repowise's `tsc` oracle emits no call made outside a function (module level) and withholds every "
      "call resolved to an abstract target (interface or type-literal member, abstract method, function-typed field), "
      "together with the function that makes it. The TypeScript rows drop the same edges from the denominator and leave "
      "those callers unjudged for precision. The stricter grading is in the diagnostic table below.")
    w("- **Rust**: repowise excludes test files by path only (`tests/` or `test/` directories) and keeps `#[cfg(test)]` code. "
      "The `path_tests_excluded` cell does the same. The `#[cfg(test)]`-excluded cell is in the diagnostic table.")
    w("- **Go**: unchanged; the cells already match (closure callees are keyed at the enclosing declaration here and at the "
      "literal in repowise, see the README).")
    w("")
    w("repowise columns are their published point estimates "
      "(`docs/BENCHMARKS.md`, repowise main, 2026-10-03) with Wilson intervals computed by us from the edge counts of the "
      "same cells in repowise-bench. **ahead / tied / behind compares the two 95% intervals** (ahead: lidx's lower bound is above "
      "repowise's upper bound; behind: lidx's upper bound is below repowise's lower bound; otherwise tied), never the point estimates.")
    w("")
    w("| Cell | lidx P [95% CI] | repowise P [95% CI] | P | lidx R [95% CI] | repowise R [95% CI] | R | oracle edges (lidx / repowise) |")
    w("|---|---|---|---|---|---|---|---|")
    for cid in ORDER:
        c = cells.get(cid)
        rw = REPOWISE.get(cid)
        if not c or not rw:
            continue
        s = comparable(c)
        pci, rci = rw_ci(rw[0], rw[3]), rw_ci(rw[1], rw[2])
        w("| %s | %.3f %s | %.3f %s | **%s** | %.3f %s | %.3f %s | **%s** | %d / %d |" % (
            cid, s["precision"], ci(s["precision_ci"]), rw[0], ci(pci), verdict(s["precision_ci"], pci),
            s["recall_comparable"], ci(s["recall_comparable_ci"]), rw[1], ci(rci), verdict(s["recall_comparable_ci"], rci),
            s["oracle_edges"], rw[2]))
    w("")
    w("Not published by repowise, so not compared: cobra without tests, the Rust cells other than `path_tests_excluded`, TypeScript with tests.")
    w("")
    w("### Stricter variants (diagnostic, no verdict)")
    w("")
    w("The same repositories graded with our own, stricter scope. They answer \"how good is lidx\", not \"how does it compare\": "
      "the repowise value shown is the one for the cell it is comparable to, for reference only.")
    w("")
    w("| Cell | Scope | lidx P [95% CI] | lidx R [95% CI] | oracle edges | repowise-comparable cell P / R |")
    w("|---|---|---|---|---:|---|")
    strict = [("ts/zod", "ts/zod", "module-level callers and abstract targets kept (dispatch counted in recall)"),
              ("ts/hono", "ts/hono", "module-level callers and abstract targets kept (dispatch counted in recall)"),
              ("rust/ripgrep/no_tests", "rust/ripgrep/path_tests_excluded", "`#[cfg(test)]` items and cfg-gated modules also excluded"),
              ("rust/fd/no_tests", "rust/fd/path_tests_excluded", "`#[cfg(test)]` items and cfg-gated modules also excluded")]
    for cid, rid, why in strict:
        c = cells.get(cid)
        if not c:
            continue
        s = c["calls"]
        cc = comparable(cells[rid]) if rid in cells else None
        ref = "%s / %s" % (pct(cc["precision"]), pct(cc["recall_comparable"])) if cc else "-"
        w("| %s | %s | %s %s | %s %s | %d | %s |" % (cid, why, pct(s["precision"]), ci(s["precision_ci"]), pct(s["recall_comparable"]),
                                                  ci(s["recall_comparable_ci"]), s["oracle_edges"], ref))
    w("")
    tsc = [(cid, comparable(cells[cid])) for cid in ("ts/zod", "ts/hono") if cid in cells]
    if tsc:
        w("TypeScript scope effect: " + "; ".join(
            "%s removes %d module-level and %d abstract-target oracle edges (%d distinct, some are both) and withholds %d lidx edges from precision (caller not judged by the oracle)"
            % (cid, s.get("module_level_removed", 0), s.get("abstract_target_removed", 0), s.get("oracle_edges_removed", 0),
               s["ungradable"].get("caller_withheld", 0)) for cid, s in tsc) + ".")
        w("")
    rs = [(cid, cells[cid]["calls"]) for cid in ("rust/ripgrep/path_tests_excluded", "rust/fd/path_tests_excluded") if cid in cells]
    if rs:
        w("Rust denominators: " + "; ".join("%s %d compiler edges here against %d in repowise-bench (%+.1f%%)" % (
            cid, s["oracle_edges"], REPOWISE[cid][2], 100 * (s["oracle_edges"] / REPOWISE[cid][2] - 1)) for cid, s in rs) + ".")
        w("")
    w("## Diagnostic columns")
    w("")
    w("`recall (static)` is over static edges whose caller and callee lidx indexes (dispatch, capture gaps out); "
      "`recall incl. dispatch` adds dispatch back; `recall comparable` is the head-to-head figure for cells graded the same way "
      "as repowise (for TypeScript the head-to-head table uses repowise's narrower scope, so its figure differs from this column).")
    w("")
    w("| Cell | Oracle | Oracle edges | static edges judged | dispatch edges | capture gap | graded lidx edges | P | recall (static) | recall incl. dispatch | recall comparable |")
    w("|---|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|")
    for cid in ORDER:
        c = cells.get(cid)
        if not c:
            continue
        s = c["calls"]
        w("| %s | %s | %d | %d | %d | %d | %d | %s | %s | %s | %s |" % (
            cid, {"go": "Go RTA", "ts": "tsc", "rust": "rust-analyzer SCIP"}[c["lang"]], s["oracle_edges"], s["oracle_edges_caller_indexed"],
            s["dispatch_edges"], s["capture_gap_edges"], s["graded"], pct(s["precision"]), pct(s["recall"]), pct(s.get("recall_strict")),
            pct(s["recall_comparable"])))
    w("")
    w("`tests` = test files are part of the analysed program and test functions are roots; `no_tests` = production code only "
      "(roots: `main`, or for a library with no `main` package its exported surface; Rust `path_tests_excluded` drops "
      "files under `tests/` or `test/` directories, Rust `no_tests` also drops `#[cfg(test)]` items and modules gated by it). lidx indexes the whole repository once; edges from files or functions the compiler did not "
      "analyse are excluded from precision and listed as ungradable.")
    w("")
    tc = meta.get("toolchains", {})
    if tc:
        w("Toolchains: " + "; ".join("%s %s" % kv for kv in tc.items()) + ".")
        w("")
    w("### Counting rules in one place")
    w("")
    w("- Oracle edges are distinct (caller declaration, callee declaration) pairs; lidx edges are deduplicated the same way.")
    w("- Callee outside the repository: not judged on either side.")
    w("- **Dispatch edges** (call through an interface or type-literal member, an abstract method, a function value, a trait "
      "method) are reported by the compiler as *possible* targets. They stay in the comparable recall; the static-recall "
      "column leaves them out.")
    w("- Oracle edge whose caller or callee is not a symbol lidx indexes (macro-generated Rust functions, nested functions): "
      "reported as a **capture gap** with its reason, out of the static recall, in the comparable recall denominator.")
    w("- lidx edge the compiler could not judge (caller file or function not in the analysed program, callee file not analysed, "
      "or a call site the compiler left unresolved): not counted for precision, listed under *ungradable*. The unresolved-site "
      "exclusion is the one that can flatter lidx; the per-cell lines below give precision if those pairs were counted wrong.")
    w("")
    w("## Alongside REFERENCES and USES")
    w("")
    w("Same grading with lidx's REFERENCES and USES edges added to CALLS (the compiler graph contains calls only, so extra "
      "edges can only cost precision; they win recall where lidx records a call as a use, e.g. TypeScript `new X()`). lidx "
      "stores REFERENCES on demand, so the table counts USES, the persisted use-site edge.")
    w("")
    w("| Cell | CALLS P | CALLS R | CALLS+REFERENCES+USES P | CALLS+REFERENCES+USES R | REFERENCES edges | USES edges |")
    w("|---|---:|---:|---:|---:|---:|---:|")
    for cid in ORDER:
        c = cells.get(cid)
        if not c:
            continue
        r = c["calls_plus_references"]
        w("| %s | %s | %s | %s | %s | %d | %d |" % (cid, pct(c["calls"]["precision"]), pct(c["calls"]["recall"]), pct(r["precision"]),
                                                  pct(r["recall"]), c["lidx_edge_counts"]["REFERENCES"], c["lidx_edge_counts"].get("USES", 0)))
    w("")
    w("## Per cell")
    for cid in ORDER:
        c = cells.get(cid)
        if not c:
            continue
        s = c["calls"]
        w("")
        w("### %s" % cid)
        w("")
        w("- oracle: %s, %d edges: %d static with an indexed caller, %d dispatch (%d of them found), %d capture gap" % (
            c.get("oracle_mode"), s["oracle_edges"], s["oracle_edges_caller_indexed"], s.get("dispatch_edges", 0), s.get("dispatch_matched", 0),
            s["capture_gap_edges"]))
        if "comparable" in c:
            cs = c["comparable"]
            w("- repowise-comparable scope: %d oracle edges (%d module-level and %d abstract-target edges removed), P %s %s, R %s %s; "
              "the figures in this section are the stricter grading" % (
                  cs["oracle_edges"], cs["module_level_removed"], cs["abstract_target_removed"], pct(cs["precision"]), ci(cs["precision_ci"]),
                  pct(cs["recall_comparable"]), ci(cs["recall_comparable_ci"])))
        w("- unresolved-site exclusion: %d lidx pairs left out; precision would be %s if they were counted wrong" % (
            s.get("unresolved_pairs_excluded", 0), pct(s.get("precision_if_unresolved_counted_wrong"))))
        w("- recall when both ends are indexed symbols: %s (%d oracle edges); caller lifted to an enclosing declaration for %d edges; capture gap reasons: %s" % (
            pct(s.get("recall_both_ends_indexed")), s.get("oracle_edges_both_ends_indexed", 0), s.get("lifted_caller_edges", 0), s.get("capture_gap_reasons") or "none"))
        w("- lidx: %d resolved in-repo CALLS pairs; %d graded (%d correct, %d wrong); lidx indexed in %ss" % (
            s["lidx_pairs_total"], s["graded"], s["tp"], s["fp"], c["index_seconds"]))
        if s["ungradable"]:
            w("- ungradable lidx pairs: " + ", ".join("%s %d" % kv for kv in sorted(s["ungradable"].items())))
        w("")
        w("| resolution_kind | graded | correct | precision | 95% CI |")
        w("|---|---:|---:|---:|---|")
        for k, v in s["by_resolution_kind"].items():
            w("| %s | %d | %d | %s | %s |" % (k, v["graded"], v["tp"], pct(v["precision"]), ci(v["ci"])))
        w("")
        w("Wrong edges (FP) by category: " + (", ".join("%s %d" % kv for kv in s["fp_categories"].items()) or "none"))
        w("")
        w("Missed edges (FN) by category: " + (", ".join("%s %d" % kv for kv in s["fn_categories"].items()) or "none"))
        w("")
        fid = cid.replace("/", "__")
        w("Lists: `results/lists/%s.fn.json`, `%s.fp.json`, `%s.capture_gap.json`, `%s.ungradable.json`, `%s.dispatch_fn.json` (the last is not committed for go/syft/tests, regenerate with run.py)." % (fid, fid, fid, fid, fid))
    sc = os.path.join(results_dir, "spotcheck.json")
    if os.path.exists(sc):
        w("")
        w(spotcheck_section(json.load(open(sc))))
    w("")
    open(os.path.join(results_dir, "report.md"), "w").write("\n".join(L))
    print("wrote", os.path.join(results_dir, "report.md"))


def spotcheck_section(sc):
    L = []
    w = L.append
    w("## Spot-check")
    w("")
    w("Everything below was read by hand against the source at the call site (seed %s; cells %s)." % (sc.get("seed"), ", ".join(sc.get("cells", []))))
    w("")
    w("**Committed edges.** 20 random wrong edges (FP) and 20 random missed edges (FN) per language. Verdicts: `lidx_error` "
      "(lidx is wrong or missed a real call), `oracle_artefact` (the compiler graph is not the right judge), `matching_artefact` "
      "(our matching rule mis-keyed a declaration).")
    w("")
    w("| Language | Sample | lidx_error | oracle_artefact | matching_artefact | artefact rate [95% Wilson CI] |")
    w("|---|---|---:|---:|---:|---|")
    tot_a = tot_n = 0
    for lang, kinds in sc["languages"].items():
        lt = {"lidx_error": 0, "oracle_artefact": 0, "matching_artefact": 0}
        for kind in ("fp", "fn"):
            items = kinds[kind]
            c = {k: sum(1 for i in items if i["verdict"] == k) for k in lt}
            for k in lt:
                lt[k] += c[k]
            n = len(items)
            art = c["oracle_artefact"] + c["matching_artefact"]
            w("| %s | %s (n=%d) | %d | %d | %d | %d/%d = %.1f%% %s |" % (lang, kind.upper(), n, c["lidx_error"], c["oracle_artefact"],
                                                                  c["matching_artefact"], art, n, 100 * art / max(n, 1), ci_pct(art, n)))
        n = sum(lt.values())
        art = lt["oracle_artefact"] + lt["matching_artefact"]
        tot_a += art
        tot_n += n
        w("| %s | both (n=%d) | %d | %d | %d | **%d/%d = %.1f%%** %s |" % (lang, n, lt["lidx_error"], lt["oracle_artefact"], lt["matching_artefact"],
                                                                    art, n, 100 * art / max(n, 1), ci_pct(art, n)))
    w("")
    bk = sc.get("buckets", {})
    if bk:
        w("**Exclusion buckets.** Up to 10 random items from every bucket that removes edges from precision or recall, per language. "
          "Verdicts: `correct_exclusion` (the bucket rule is right for this item) or `misbucketed` (the item should have been "
          "graded, so the exclusion flatters or hides something).")
        w("")
        w("| Language | Bucket | Bucket size | Sampled | misbucketed | rate [95% Wilson CI] |")
        w("|---|---|---:|---:|---:|---|")
        bm = bn = 0
        for lang, names in bk.items():
            for name, items in names.items():
                n = len(items)
                if not n:
                    continue
                mb = sum(1 for i in items if i["verdict"] == "misbucketed")
                bm += mb
                bn += n
                w("| %s | %s | %d | %d | %d | %.1f%% %s |" % (lang, name, items[0]["bucket_size"], n, mb, 100 * mb / n, ci_pct(mb, n)))
        w("| all | all buckets | | %d | %d | **%.1f%%** %s |" % (bn, bm, 100 * bm / max(bn, 1), ci_pct(bm, bn)))
        w("")
        tot_a += bm
        tot_n += bn
    w("Pooled over every sampled item: %d/%d = %.1f%% %s." % (tot_a, tot_n, 100 * tot_a / max(tot_n, 1), ci_pct(tot_a, tot_n)))
    w("")
    w(sc.get("notes", ""))
    w("")
    for lang, kinds in sc["languages"].items():
        w("### %s samples" % lang)
        w("")
        for kind in ("fp", "fn"):
            w("**%s**" % kind.upper())
            w("")
            for i in kinds[kind]:
                w("- `%s` %s -> %s: **%s**, %s" % (i["id"], i["caller"], i["callee"], i["verdict"], i["note"]))
            w("")
        for name, items in bk.get(lang, {}).items():
            w("**bucket %s**" % name)
            w("")
            for i in items:
                w("- `%s` %s -> %s: **%s**, %s" % (i["id"], i["caller"], i["callee"], i["verdict"], i["note"]))
            w("")
    return "\n".join(L)


def ci_pct(k, n):
    lo, hi = wilson(k, n)
    return "[%.1f%%, %.1f%%]" % (100 * lo, 100 * hi) if lo is not None else ""
