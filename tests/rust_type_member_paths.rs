//! Issue #437: calls whose callee is a std or generated member bind to no
//! same-named method of an unrelated repo type. One fixture per shape the
//! held-out `tokei` cell showed: `Type::default()` of a derived `Default`,
//! `Type::item` of a type the index does not declare, turbofished std
//! methods, `Vec<_>` locals, `<_>::deserialize`, a map iterated through
//! `mem::replace`, a builder from an outside crate, plus the bindings that
//! must stay (inherited trait defaults, enum-variant receivers, type
//! aliases, trait methods on std types, module-qualified calls).

mod common;

use std::collections::BTreeSet;

fn targets(files: &[(&str, &str)], caller: &str) -> BTreeSet<String> {
    common::call_targets(files, caller).into_iter().collect()
}

fn lib(src: &str) -> Vec<(&str, &str)> {
    vec![
        ("Cargo.toml", "[package]\nname = \"x\"\n"),
        ("src/lib.rs", src),
    ]
}

fn bound(got: &BTreeSet<String>, target: &str) -> bool {
    got.contains(target)
}

fn no_repo_binding(got: &BTreeSet<String>) -> bool {
    got.iter().all(|t| !t.starts_with("crate::"))
}

const NUMBER_STYLE: &str = "pub struct NumberStyle;\n\
impl Default for NumberStyle {\n    fn default() -> Self { NumberStyle }\n}\n";

#[test]
fn derived_default_of_self_is_not_another_types_default() {
    let src = format!(
        "{NUMBER_STYLE}#[derive(Default)]\npub struct Config {{ pub a: u32 }}\n\
         impl Config {{\n    pub fn make() -> Self {{\n        Self::default()\n    }}\n}}\n"
    );
    let got = targets(&lib(&src), "crate::Config::make");
    assert!(no_repo_binding(&got), "{got:#?}");
}

#[test]
fn derived_default_of_a_named_type_is_not_another_types_default() {
    let src = format!(
        "{NUMBER_STYLE}#[derive(Default)]\npub struct Config {{ pub a: u32 }}\n\
         pub fn make() -> Config {{\n    let c = Config::default();\n    c\n}}\n\
         pub fn spread() -> Config {{\n    Config {{ a: 1, ..Config::default() }}\n}}\n"
    );
    for caller in ["crate::make", "crate::spread"] {
        let got = targets(&lib(&src), caller);
        assert!(no_repo_binding(&got), "{caller}: {got:#?}");
    }
}

