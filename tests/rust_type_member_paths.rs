/// `rpc::f()` through `use super::*`, with `f` declared in a submodule of
/// `rpc` and re-exported: a repo item, not an external stub.
#[test]
fn glob_imported_module_path_binds_the_reexported_function() {
    let tree = vec![
        ("Cargo.toml", "[package]\nname = \"x\"\n"),
        (
            "src/lib.rs",
            "pub mod rpc;\nuse crate::rpc;\nmod tests_like {\n    use super::*;\n    pub fn go() -> u32 { rpc::method_param_schema(\"x\") }\n}\n",
        ),
        (
            "src/rpc/mod.rs",
            "mod schema;\npub use schema::method_param_schema;\n",
        ),
        (
            "src/rpc/schema.rs",
            "pub fn method_param_schema(m: &str) -> u32 { 0 }\n",
        ),
    ];
    let (_tmp, root, db_path) = common::index_repo("lidx-glob-module-", &tree);
    let indexer = lidx::indexer::Indexer::new(root, db_path).unwrap();
    let gv = indexer.db().current_graph_version().unwrap();
    let conn = indexer.db().read_conn().unwrap();
    let rows: Vec<(String, String)> = conn
        .prepare(
            "SELECT COALESCE(t.qualname, ''), COALESCE(t.kind, '') FROM edges e
             JOIN symbols s ON s.id = e.source_symbol_id
             LEFT JOIN symbols t ON t.id = e.target_symbol_id
             WHERE e.graph_version = ? AND e.kind = 'CALLS'
               AND s.qualname = 'crate::tests_like::go'",
        )
        .unwrap()
        .query_map([gv], |r| Ok((r.get(0)?, r.get(1)?)))
        .unwrap()
        .map(|r| r.unwrap())
        .collect();
    assert_eq!(
        rows,
        vec![(
            "crate::rpc::schema::method_param_schema".to_string(),
            "function".to_string()
        )]
    );
}

