/// A repo trait's blanket impl provides `greet` to every `Marker` type; the
/// UFCS path `P::greet(&P)` is a repo-side miss, never an external stub.
#[test]
fn blanket_impl_method_path_is_not_an_external_stub() {
    let tree = vec![
        ("Cargo.toml", "[package]\nname = \"x\"\n"),
        (
            "src/lib.rs",
            "pub trait Marker {}\npub trait Greets { fn greet(&self) -> u32 { 3 } }\nimpl<T: Marker> Greets for T {}\npub struct P;\nimpl Marker for P {}\npub fn go() -> u32 { P::greet(&P) }\n",
        ),
    ];
    let (_tmp, root, db_path) = common::index_repo("lidx-blanket-", &tree);
    let indexer = lidx::indexer::Indexer::new(root, db_path).unwrap();
    let gv = indexer.db().current_graph_version().unwrap();
    let conn = indexer.db().read_conn().unwrap();
    let stubs: i64 = conn
        .query_row(
            "SELECT COUNT(*) FROM edges e JOIN symbols t ON t.id = e.target_symbol_id
             WHERE e.graph_version = ? AND e.kind = 'CALLS' AND t.kind = 'external'
               AND t.qualname LIKE 'ext:P::%'",
            [gv],
            |r| r.get(0),
        )
        .unwrap();
    assert_eq!(stubs, 0);
}

