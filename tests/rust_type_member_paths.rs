#[test]
fn rust_call_never_binds_a_symbol_of_another_language() {
    let tree = vec![
        ("Cargo.toml", "[package]\nname = \"x\"\n"),
        (
            "src/lib.rs",
            "pub enum Style { Auto }\npub fn go() {\n    Style::Auto.components(true);\n}\n",
        ),
        ("db/schema.sql", "CREATE TABLE components (id int);\n"),
    ];
    let got = targets(&tree, "crate::go");
    assert!(
        got.iter()
            .all(|t| !t.ends_with("components") || t == "components"),
        "{got:#?}"
    );
    let (_tmp, root, db_path) = common::index_repo("lidx-rust-sql-", &tree);
    let indexer = lidx::indexer::Indexer::new(root, db_path).unwrap();
    let gv = indexer.db().current_graph_version().unwrap();
    let conn = indexer.db().read_conn().unwrap();
    let cross: i64 = conn
        .query_row(
            "SELECT COUNT(*) FROM edges e
             JOIN files sf ON sf.id = e.file_id
             JOIN symbols t ON t.id = e.target_symbol_id
             JOIN files tf ON tf.id = t.file_id
             WHERE e.graph_version = ? AND e.kind = 'CALLS' AND sf.language = 'rust'
               AND tf.language <> 'rust'",
            [gv],
            |r| r.get(0),
        )
        .unwrap();
    assert_eq!(cross, 0, "a Rust call bound to a SQL symbol");
}

